"""Step 3 of the eta study: proposed multiple-scattering tables eta(range) per Vaisala type, in the
format of calibration/cloud/_filters._ETA_CL31/_CL51/_CL61 (this script does NOT touch _filters.py).

Central table: PVC (Hogan 2006; validation/multiple_scattering_eta.py, type OPTICS / WAVELENGTH) at
a_G = 3.3 um (Cloudnet, step 1d) and alpha = the type's network median alpha_k (ceilometer tail slope,
step 2), on the operational CBH nodes (0.25 .. 2.375 km).
Uncertainty band from N_DRAWS Monte-Carlo draws (16th / 84th percentiles = +-1 sigma):
  a_G     ~ uniform(2.5, 5.0) um
  alpha   ~ uniform(P10, P90) of the type's per-unit median alpha_k
  FOV / divergence convention: the manufacturer "+-" values (Wiegner et al. 2014 Table 1 "half angle",
          Vaisala divergence) are used as top-hat edge (rho_t) and 1/e (rho_l) half-angles for the central
          table; whether they are edge, 1/e or 1/e^2 widths (or full angles) is unknown, so rho_t and rho_l
          are each drawn log-uniformly between /sqrt(2) and x sqrt(2) of the documented value (independent)
  PVC model error: eta x (1 + N(0, 0.020))
Also: level and CBH-slope change of C_L against the operational table at 0.5 / 1 / 2 km
(C_L scales with eta at the cloud base: dC_L/C_L = eta_new/eta_oper - 1).

Run:  python validation/eta_study/eta_tables_proposed.py --alpha-k CL31=..,CL51=..,CL61=.. \
          --alpha-k-range CL31=lo:hi,CL51=lo:hi,CL61=lo:hi [--workers 10]
Output: C:/DATA/Projects/202611_eta_study/step3/ (eta_tables_proposed.py.txt, eta_tables_proposed.csv,
        eta_change_vs_operational.csv, fig_eta_tables_proposed.png)
"""
from __future__ import annotations

import os
for _v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"):
    os.environ[_v] = "1"

import argparse
import sys
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))

OUT = Path("C:/DATA/Projects/202611_eta_study/step3")
TYPES = ("CL31", "CL51", "CL61")
A_G = 3.3
N_DRAWS = 300
SIG_MODEL = 0.020
CONV_FACTOR = np.sqrt(2.0)        # optics convention range: documented value / or x this factor
SEED = 20261102


def nodes():
    from calibration.cloud._filters import _ETA_CL31
    return _ETA_CL31[:, 0].copy()                        # 0.25 .. 2.375 km, same for every type


def eta_curve(args):
    itype, a_um, alpha_km, f_t, f_l = args
    from validation.multiple_scattering_eta import OPTICS, WAVELENGTH, eta_for_cloud_base
    rho_t, rho_l = OPTICS[itype]
    th = WAVELENGTH[itype] / (np.pi * a_um * 1e-6)
    return np.array([eta_for_cloud_base(z * 1000.0, rho_t * f_t, rho_l * f_l, th, alpha=alpha_km * 1e-3)
                     for z in nodes()])


def main():
    import pandas as pd
    import calibration.cloud._filters as CF
    ap = argparse.ArgumentParser()
    ap.add_argument("--alpha-k", required=True)
    ap.add_argument("--alpha-k-range", required=True)
    ap.add_argument("--workers", type=int, default=10)
    a = ap.parse_args()
    ak = {kv.split("=")[0]: float(kv.split("=")[1]) for kv in a.alpha_k.split(",")}
    rng_ak = {kv.split("=")[0]: tuple(float(v) for v in kv.split("=")[1].split(":")) for kv in a.alpha_k_range.split(",")}
    OUT.mkdir(parents=True, exist_ok=True)
    z = nodes()
    oper = {"CL31": CF._ETA_CL31, "CL51": CF._ETA_CL51, "CL61": CF._ETA_CL61}
    rng = np.random.default_rng(SEED)
    jobs, draws = [], {}
    for it in TYPES:
        ag = rng.uniform(2.5, 5.0, N_DRAWS)
        al = rng.uniform(*rng_ak[it], N_DRAWS)
        f_t = np.exp(rng.uniform(-np.log(CONV_FACTOR), np.log(CONV_FACTOR), N_DRAWS))
        f_l = np.exp(rng.uniform(-np.log(CONV_FACTOR), np.log(CONV_FACTOR), N_DRAWS))
        draws[it] = dict(ag=ag, al=al, mod=rng.normal(0, SIG_MODEL, N_DRAWS))
        jobs.append((it, A_G, ak[it], 1.0, 1.0))
        jobs += [(it, g, l, ft, fl) for g, l, ft, fl in zip(ag, al, f_t, f_l)]
    with ProcessPoolExecutor(max_workers=a.workers) as ex:
        res = list(ex.map(eta_curve, jobs, chunksize=8))
    lines = ["# Proposed eta(range) tables (PVC, a_G 3.3 um, alpha = network median alpha_k), same format as",
             "# calibration/cloud/_filters._ETA_<type>. _LO / _HI = 16th / 84th percentile of the Monte-Carlo band",
             f"# (a_G U(2.5,5) um, alpha U(P10,P90) of unit medians, rho_t and rho_l log-uniform /sqrt2..x sqrt2 for the",
             f"# unknown FOV/divergence convention, PVC model {SIG_MODEL:.0%}). Central optics: Wiegner 2014 half-angle, top-hat edge.",
             "# Generated by validation/eta_study/eta_tables_proposed.py -- NOT applied to the operational code.", ""]
    rows, chg = [], []
    k = 0
    for it in TYPES:
        central = res[k]
        k += 1
        mc = np.array(res[k:k + N_DRAWS])
        k += N_DRAWS
        d = draws[it]
        mc = mc * (1 + d["mod"][:, None])
        lo, hi = np.percentile(mc, [16, 84], axis=0)
        for name, arr in (("", central), ("_LO", lo), ("_HI", hi)):
            lines.append(f"_ETA_{it}_PROPOSED{name} = np.array([\n    " +
                         ",\n    ".join(", ".join(f"[{zz:.3f}, {e:.5f}]" for zz, e in zip(z[i:i + 4], arr[i:i + 4]))
                                        for i in range(0, z.size, 4)) + "])")
        lines.append("")
        for zz, c, l_, h_, o in zip(z, central, lo, hi, oper[it][:, 1]):
            rows.append(dict(itype=it, cbh_km=zz, eta_proposed=c, eta_lo=l_, eta_hi=h_, eta_operational=o))
        for zk in (0.5, 1.0, 2.0):
            e_new = float(np.interp(zk, z, central))
            e_op = float(np.interp(zk, oper[it][:, 0], oper[it][:, 1]))
            e_lo, e_hi = float(np.interp(zk, z, lo)), float(np.interp(zk, z, hi))
            chg.append(dict(itype=it, cbh_km=zk, alpha_k=ak[it], eta_operational=e_op, eta_proposed=e_new,
                            eta_lo=e_lo, eta_hi=e_hi, dCL_pct=100 * (e_new / e_op - 1),
                            dCL_lo_pct=100 * (e_lo / e_op - 1), dCL_hi_pct=100 * (e_hi / e_op - 1)))
    (OUT / "eta_tables_proposed.py.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    pd.DataFrame(rows).to_csv(OUT / "eta_tables_proposed.csv", index=False, float_format="%.5f")
    c = pd.DataFrame(chg)
    slope = c.groupby("itype").apply(lambda g: (g.set_index("cbh_km").dCL_pct[2.0] - g.set_index("cbh_km").dCL_pct[0.5]) / 1.5)
    c.to_csv(OUT / "eta_change_vs_operational.csv", index=False, float_format="%.4f")
    print("\n".join(lines))
    print(c.round(3).to_string(index=False))
    print("CBH-slope change of C_L vs operational, 0.5 -> 2 km (%/km):\n" + slope.round(2).to_string())
    figure(pd.DataFrame(rows), oper)


def figure(df, oper):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import calibration.cloud._filters as CF
    leg = {"CL31": CF._ETA_LEGACY_CL31, "CL51": CF._ETA_LEGACY_CL51, "CL61": CF._ETA_LEGACY_CL51}
    fig, axes = plt.subplots(1, 3, figsize=(17, 5.6), sharey=True)
    for ax, it in zip(axes, TYPES):
        g = df[df.itype == it]
        ax.fill_betweenx(g.cbh_km, g.eta_lo, g.eta_hi, color="C2", alpha=0.25, label="proposed +-1 sigma")
        ax.plot(g.eta_proposed, g.cbh_km, "-o", color="C2", lw=2, label="proposed PVC a_G 3.3 / alpha_k")
        ax.plot(oper[it][:, 1], oper[it][:, 0], "-s", color="k", label="operational PVC 5.5 um / 10 /km")
        ax.plot(leg[it][:, 1], leg[it][:, 0], "--", color="C1", label="legacy Hopkin")
        ax.set_title(it)
        ax.set_xlabel("eta")
        ax.grid(alpha=0.3)
        ax.legend(fontsize=8)
    axes[0].set_ylabel("cloud-base range [km]")
    fig.suptitle("Step 3: proposed eta(range) tables vs operational and legacy", fontweight="bold")
    fig.tight_layout(rect=(0, 0, 1, 0.93))
    fig.savefig(OUT / "fig_eta_tables_proposed.png", dpi=140)
    plt.close(fig)


if __name__ == "__main__":
    main()
